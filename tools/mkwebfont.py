#!/usr/bin/env python3
"""Rasterize the browser's fonts: proportional DejaVu Sans (regular, bold,
oblique, bold oblique) and DejaVu Sans Mono (regular, bold), at the sizes
pages ask for most, into src/user/gen/webfont.bin (8-bit coverage) and
src/user/gen/webfont.inc (the tables that find a glyph).

    python tools/mkwebfont.py [fonts directory]

DejaVu fonts: Bitstream Vera license and public domain changes; free to
copy, embed and redistribute.

webfont.inc:
  WF_FACES, WF_SIZES, WF_GLYPHS, wf_size_px (WF_SIZES bytes)
  wf_fonts: WF_FACES * WF_SIZES entries of WFT_SIZE bytes (face-major):
    WFT_GLYPHS dq  offset of its glyph table in webfont.bin
    WFT_ASCENT dd  pixels above the baseline
    WFT_DESCENT dd pixels below it
    WFT_LINE   dd  line height, pixels
    WFT_SPACE  dd  a space's advance, 1/64 pixels
  a glyph table: WF_GLYPHS entries of WG_SIZE bytes:
    WG_DATA dd   offset of its coverage in webfont.bin (w * h bytes)
    WG_ADV  dw   advance, 1/64 pixels
    WG_W    db, WG_H db   bitmap size
    WG_LEFT db (signed)   from the pen to the bitmap's left
    WG_TOP  db (signed)   from the baseline up to the bitmap's top
  wf_low: 256 words, the glyph of U+0000..U+00FF (0: none)
  wf_high: WF_HIGH entries of (dd code point, dd glyph), sorted
Glyph 0 is the replacement, drawn for anything missing.
"""
import pathlib
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "user" / "gen"
FONTS = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(r"C:\Windows\Fonts")

FACES = ["DejaVuSans.ttf", "DejaVuSans-Bold.ttf", "DejaVuSans-Oblique.ttf",
         "DejaVuSans-BoldOblique.ttf", "DejaVuSansMono.ttf", "DejaVuSansMono-Bold.ttf"]
FACE_NAMES = ["SANS", "BOLD", "ITALIC", "BOLD_ITALIC", "MONO", "MONO_BOLD"]
SIZES = [13, 16, 20, 24, 28, 36]

EXTRA = (list(range(0x2010, 0x2016)) + [0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E,
         0x2020, 0x2021, 0x2022, 0x2026, 0x2030, 0x2032, 0x2033, 0x2039, 0x203A, 0x20AC,
         0x2122, 0x21BB, 0x2190, 0x2191, 0x2192, 0x2193, 0x2194, 0x21D2, 0x2212, 0x2215, 0x221A,
         0x221E, 0x2248, 0x2260, 0x2264, 0x2265, 0x25A0, 0x25A1, 0x25B2, 0x25B6, 0x25BC,
         0x25C0, 0x25CB, 0x25CF, 0x2605, 0x2606, 0x2713, 0x2714, 0x2715, 0x2717, 0x2718,
         0x0152, 0x0153, 0x0160, 0x0161, 0x0178, 0x017D, 0x017E, 0x0192, 0x02C6, 0x02DC,
         0xFFFD]
         + list(range(0x0100, 0x0180))          # Latin Extended-A
         + list(range(0x0391, 0x03CA))          # Greek
         + list(range(0x0400, 0x0460)))         # Cyrillic


def main():
    codes = [None] + list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + sorted(set(EXTRA))
    index = {c: i for i, c in enumerate(codes) if c is not None}
    blob = bytearray()
    tables = []
    for face in FACES:
        for px in SIZES:
            font = ImageFont.truetype(str(FONTS / face), px)
            ascent, descent = font.getmetrics()
            table = bytearray()
            for c in codes:
                ch = chr(c if c is not None else 0xFFFD)
                adv = round(font.getlength(ch) * 64)
                x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
                w, h = max(0, x1 - x0), max(0, y1 - y0)
                off = len(blob)
                if w and h:
                    img = Image.new("L", (w, h), 0)
                    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
                    blob += img.tobytes()
                table += struct.pack("<IHBBbbH", off, adv, w, h, x0, -y0, 0)
            blob += bytes(-len(blob) % 4)
            tables.append((len(blob), ascent, descent, ascent + descent,
                           round(font.getlength(" ") * 64), table))
            blob += table
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "webfont.bin").write_bytes(bytes(blob))
    low = [0] * 256
    high = []
    for c, i in index.items():
        if c < 256:
            low[c] = i
        else:
            high.append((c, i))
    lines = ["; generated by tools/mkwebfont.py - do not edit",
             "; DejaVu Sans and Sans Mono (Bitstream Vera license)",
             f"WF_FACES        equ {len(FACES)}",
             f"WF_SIZES        equ {len(SIZES)}",
             f"WF_GLYPHS       equ {len(codes)}",
             f"WF_HIGH         equ {len(high)}",
             "WFT_GLYPHS      equ 0", "WFT_ASCENT      equ 8", "WFT_DESCENT     equ 12",
             "WFT_LINE        equ 16", "WFT_SPACE       equ 20", "WFT_SIZE        equ 24",
             "WG_DATA         equ 0", "WG_ADV          equ 4", "WG_W            equ 6",
             "WG_H            equ 7", "WG_LEFT         equ 8", "WG_TOP          equ 9",
             "WG_SIZE         equ 12"]
    for i, n in enumerate(FACE_NAMES):
        lines.append(f"WF_{n:<12} equ {i}")
    for i, px in enumerate(SIZES):
        lines.append(f"WF_PX{px:<10} equ {i}")
    lines.append("align 8")
    lines.append("wf_fonts:")
    for off, a, d, line, space, _ in tables:
        lines.append(f"    dq {off}")
        lines.append(f"    dd {a}, {d}, {line}, {space}")
    lines.append("wf_size_px: db " + ", ".join(map(str, SIZES)))
    lines.append("align 4")
    lines.append("wf_high:")
    for c, i in sorted(high):
        lines.append(f"    dd 0x{c:04X}, {i}")
    lines.append("wf_low:")
    for k in range(0, 256, 16):
        lines.append("    dw " + ", ".join(str(v) for v in low[k:k + 16]))
    (OUT / "webfont.inc").write_text("\n".join(lines) + "\n", newline="\n")
    print(f"webfont: {len(FACES)} faces x {len(SIZES)} sizes x {len(codes)} glyphs, {len(blob):,} bytes")


if __name__ == "__main__":
    main()
