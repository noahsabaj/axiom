#!/usr/bin/env python3
"""Rasterize compose's fonts at twice the browser's sizes, for screens drawn
at two pixels a point: the same DejaVu faces and glyphs as
tools/mkwebfont.py, at 26, 32, 40, 48, 56 and 72 pixels. Those glyphs
follow webfont.bin's, as one font file of twelve sizes, packed
(PackBits: a byte n < 128, then n + 1 bytes as they are; a byte n >= 128,
then one byte, n - 125 times) into src/user/gen/docfont.pak, which compose
unpacks as it starts (a program is 16 MiB at most, and the two unpacked
are 28 MB). src/user/gen/docfont.inc has the tables of both, and WF_BYTES,
their size unpacked (web/draw.inc assembles them so when WF_DOC is
defined).

    python tools/mkdocfont.py [fonts directory]

webfont.bin is not made again: its tables are read from webfont.inc, so
make this again whenever webfont.bin is made again (tools/build.py makes
it if it is not there).
"""
import pathlib
import re
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mkwebfont as web  # noqa: E402

OUT = web.OUT
FONTS = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else web.FONTS
SIZES = [px * 2 for px in web.SIZES]


def web_tables():
    """webfont.inc's wf_fonts: (offset, ascent, descent, line, space) each."""
    text = (OUT / "webfont.inc").read_text()
    body = text[text.index("wf_fonts:"):text.index("wf_size_px:")]
    offs = [int(v) for v in re.findall(r"dq (\d+)", body)]
    rest = [tuple(int(x) for x in m.split(",")) for m in re.findall(r"dd ([\d, ]+)", body)]
    assert len(offs) == len(rest) == len(web.FACES) * len(web.SIZES)
    return [(o, *r) for o, r in zip(offs, rest)]


def packbits(data):
    out = bytearray()
    i, n = 0, len(data)
    while i < n:
        j = i
        while j < n and j - i < 130 and data[j] == data[i]:
            j += 1
        if j - i >= 3:
            out += bytes((0x80 + j - i - 3, data[i]))
            i = j
            continue
        j = i
        while j < n and j - i < 128 and not (j + 2 < n and data[j] == data[j + 1] == data[j + 2]):
            j += 1
        out.append(j - i - 1)
        out += data[i:j]
        i = j
    return bytes(out)


def main():
    base = (OUT / "webfont.bin").stat().st_size
    codes = [None] + list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + sorted(set(web.EXTRA))
    index = {c: i for i, c in enumerate(codes) if c is not None}
    blob = bytearray()
    tables = []
    for face in web.FACES:
        for px in SIZES:
            font = ImageFont.truetype(str(FONTS / face), px)
            ascent, descent = font.getmetrics()
            table = bytearray()
            for c in codes:
                ch = chr(c if c is not None else 0xFFFD)
                adv = round(font.getlength(ch) * 64)
                x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
                w, h = max(0, x1 - x0), max(0, y1 - y0)
                assert w < 256 and h < 256 and -128 <= x0 < 128 and -128 <= -y0 < 128
                off = base + len(blob)
                if w and h:
                    img = Image.new("L", (w, h), 0)
                    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
                    blob += img.tobytes()
                table += struct.pack("<IHBBbbH", off, adv, w, h, x0, -y0, 0)
            blob += bytes(-(base + len(blob)) % 4)
            tables.append((base + len(blob), ascent, descent, ascent + descent,
                           round(font.getlength(" ") * 64)))
            blob += table
    whole = (OUT / "webfont.bin").read_bytes() + bytes(blob)
    (OUT / "docfont.pak").write_bytes(packbits(whole))

    old = web_tables()
    sizes = sorted(web.SIZES + SIZES)
    order = [(1, web.SIZES.index(px)) if px in web.SIZES else (2, SIZES.index(px)) for px in sizes]
    low = [0] * 256
    high = []
    for c, i in index.items():
        if c < 256:
            low[c] = i
        else:
            high.append((c, i))
    lines = ["; generated by tools/mkdocfont.py - do not edit",
             "; DejaVu Sans and Sans Mono (Bitstream Vera license): webfont.bin's",
             "; sizes and twice them, as one font file (docfont.pak, unpacked)",
             f"WF_BYTES        equ {len(whole)}",
             f"WF_FACES        equ {len(web.FACES)}",
             f"WF_SIZES        equ {len(sizes)}",
             f"WF_GLYPHS       equ {len(codes)}",
             f"WF_HIGH         equ {len(high)}",
             "WFT_GLYPHS      equ 0", "WFT_ASCENT      equ 8", "WFT_DESCENT     equ 12",
             "WFT_LINE        equ 16", "WFT_SPACE       equ 20", "WFT_SIZE        equ 24",
             "WG_DATA         equ 0", "WG_ADV          equ 4", "WG_W            equ 6",
             "WG_H            equ 7", "WG_LEFT         equ 8", "WG_TOP          equ 9",
             "WG_SIZE         equ 12"]
    for i, n in enumerate(web.FACE_NAMES):
        lines.append(f"WF_{n:<12} equ {i}")
    for i, px in enumerate(sizes):
        lines.append(f"WF_PX{px:<10} equ {i}")
    lines.append("align 8")
    lines.append("wf_fonts:")
    n = len(web.SIZES)
    for f in range(len(web.FACES)):
        for which, k in order:
            off, a, d, line, space = (old if which == 1 else tables)[f * n + k]
            lines.append(f"    dq {off}")
            lines.append(f"    dd {a}, {d}, {line}, {space}")
    lines.append("wf_size_px: db " + ", ".join(map(str, sizes)))
    lines.append("align 4")
    lines.append("wf_high:")
    for c, i in sorted(high):
        lines.append(f"    dd 0x{c:04X}, {i}")
    lines.append("wf_low:")
    for k in range(0, 256, 16):
        lines.append("    dw " + ", ".join(str(v) for v in low[k:k + 16]))
    (OUT / "docfont.inc").write_text("\n".join(lines) + "\n", newline="\n")
    print(f"docfont: {len(web.FACES)} faces x {len(SIZES)} sizes x {len(codes)} glyphs, "
          f"{len(blob):,} bytes, after webfont.bin's {base:,}; packed, "
          f"{(OUT / 'docfont.pak').stat().st_size:,}")


if __name__ == "__main__":
    main()
